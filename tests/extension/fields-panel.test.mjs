import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { parseHTML } from 'linkedom';
import { diskFolder } from './folder-fixture.mjs';
import { openFolder, createFolderRepository } from '../../extension/folder-store.js';
import { createFields } from '../../extension/core.js';

test('side panel edits metadata, summary, quotation and later understanding without losing the composer draft', async t => {
  const { window, document } = parseHTML(await readFile(new URL('../../extension/panel.html', import.meta.url), 'utf8'));
  globalThis.window = window; globalThis.document = document;
  window.HTMLElement.prototype.showModal = function() { this.open = true; };
  window.HTMLElement.prototype.close = function() { this.open = false; this.dispatchEvent(new window.Event('close')); };
  const disk = await diskFolder(t), target = await openFolder(disk.root), repo = createFolderRepository(disk.root, target.id);
  const fields = { ...createFields({ url: 'https://example.com/a', title: '原始标题' }), status: 'read', summary: '旧摘录', thought: '旧想法' };
  let { note } = await repo.request({ method: 'POST', body: { id: crypto.randomUUID(), fields } });
  const clip = { id: crypto.randomUUID(), text: '原始引用', thought: '自己的想法', images: [], sourceUrl: fields.sources[0].url, sourceTitle: fields.title, createdAt: new Date().toISOString(), videoTime: null, anchor: { exact: '原始引用' } };
  note = (await repo.request({ method: 'PATCH', body: { id: note.id, revision: note.revision, action: 'add_clip', clip } })).note;
  const { adapter } = await import('../../extension/adapter.js');
  const storage = new Map([['activeNoteId', note.id], ['draft:' + note.id, { thought: '尚未保存的写作草稿' }]]);
  adapter.read = async key => structuredClone(storage.get(key));
  adapter.write = async (key, value) => storage.set(key, structuredClone(value));
  adapter.remove = async key => storage.delete(key);
  adapter.cloud = repo.request; adapter.subscribe = () => {}; adapter.pending = async () => null;
  adapter.job = async () => null; adapter.page = async () => ({ id: 1, url: fields.sources[0].url, title: fields.title });
  const interval = globalThis.setInterval; globalThis.setInterval = () => 1;
  try { await import('../../extension/panel.js'); } finally { globalThis.setInterval = interval; }
  const until = async check => { for (let i = 0; i < 100; i++) { if (await check()) return; await new Promise(r => setTimeout(r, 10)); } assert.fail('Panel did not settle: ' + document.querySelector('#notice')?.textContent); };
  const click = selector => { const el = document.querySelector(selector); assert.ok(el, selector); el.dispatchEvent(new window.Event('click', { bubbles: true })); };
  const current = async () => (await repo.request({})).notes.find(n => n.id === note.id);
  const change = (selector, value) => { const el = document.querySelector(selector); el.value = value; el.dispatchEvent(new window.Event('input', { bubbles: true })); };
  await until(() => document.querySelector('[data-action="edit-metadata"]'));
  click('[data-action="edit-metadata"]'); await until(() => document.querySelector('.note-metadata-editor').open);
  for (const name of ['title', 'published', 'timestamp', 'kind', 'status']) assert.ok(document.querySelector(`[name=${name}]`));
  change('[name=published]', '2026.11'); change('[name=title]', '修改标题');
  // linkedom has no writable select.value; the browser supplies it natively.
  for (const [name, value] of [['kind', 'article'], ['status', 'read']]) Object.defineProperty(document.querySelector(`[name=${name}]`), 'value', { value, writable: true });
  document.querySelector('.note-metadata-editor form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
  await until(() => !document.querySelector('.note-metadata-editor').open);
  assert.match(document.querySelector('.note-publication').textContent, /2026.11/);
  assert.equal((await current()).title, '修改标题');
  click('[data-kind=core]'); await until(() => document.querySelector('#manual-summary .record-editor'));
  change('#manual-summary .record-text', '**核心判断**与代码 `value`');
  click('#manual-summary [data-edit=save]'); await until(() => !document.querySelector('.record-editor'));
  assert.equal((await current()).coreSummary.text, '**核心判断**与代码 `value`');
  assert.equal(document.querySelector('#manual-summary strong').textContent, '核心判断');
  click('[data-action=edit-record]'); await until(() => document.querySelector('.record-editor'));
  change('.record-editor .record-text', '修改后的完整引用');
  click('.record-editor [data-edit=save]'); await until(() => !document.querySelector('.record-editor'));
  assert.equal((await current()).clips[0].text, '修改后的完整引用');
  assert.equal((await current()).clips[0].anchor, undefined);
  assert.equal((await current()).clips[0].thought, '自己的想法');
  click('[data-kind=new-review]'); await until(() => document.querySelector('.record-editor'));
  change('.record-editor .record-text', '回顾后补充的判断');
  click('.record-editor [data-edit=save]'); await until(() => !document.querySelector('.record-editor'));
  assert.equal((await current()).reviews[0].text, '回顾后补充的判断');
  assert.ok(document.querySelector('[data-kind=review]'));
  assert.ok(document.querySelector('[data-kind=legacy]'));
  assert.equal(document.querySelector('#thought').value, '尚未保存的写作草稿');
  const reopened = (await createFolderRepository(disk.root, target.id).request({})).notes[0];
  assert.equal(reopened.published, '2026.11'); assert.equal(reopened.reviews.length, 1);
});
